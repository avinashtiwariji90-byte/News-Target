export function getRashiById(id: string): RashiItem | undefined {
  return RASHIFAL_LIST.find(r => r.id.toLowerCase() === id.toLowerCase() || r.nameHi === id);
}

export function getFormattedTodayHindi(): string {
  const date = new Date();
  const monthsHindi = [
    'जनवरी', 'फरवरी', 'मार्च', 'अप्रैल', 'मई', 'जून',
    'जुलाई', 'अगस्त', 'सितंबर', 'अक्टूबर', 'नवंबर', 'दिसंबर'
  ];
  const daysHindi = ['रविवार', 'सोमवार', 'मंगलवार', 'बुधवार', 'गुरुवार', 'शुक्रवार', 'शनिवार'];
  const day = date.getDate();
  const month = monthsHindi[date.getMonth()];
  const year = date.getFullYear();
  const weekday = daysHindi[date.getDay()];
  return `${day} ${month} ${year}, ${weekday}`;
}

